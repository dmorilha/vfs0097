static bool sha256_hmac_compare(const std::span<const uint8_t> & buffer, const std::span<const uint8_t> & key, const std::span<const uint8_t, 0x20> & digest) {
  assert(!key.empty());
  assert(!buffer.empty());
  std::array<uint8_t, 0x20> other_digest;
  size_t length = 0;
  unsigned char * const result_code = EVP_Q_mac(
      /* OSSL_LIB_CTX *libctx = */ nullptr,
      /* const char *name = */ "HMAC",
      /* const char *propq = */ nullptr,
      /* const char *subalg = */ "SHA256",
      /* const OSSL_PARAM *params = */ nullptr,
      /* const void *key = */ key.data(), /* size_t keylen = */ key.size(),
      /* const unsigned char *data = */ buffer.data(), /* size_t datalen = */ buffer.size(),
      /* unsigned char *out = */ other_digest.data(), /* size_t outsize = */ other_digest.size(),
      /* size_t *outlen = */ &length);
  assert(0 < length);
  assert(nullptr != result_code);
  return 0 == memcmp(digest.data(), other_digest.data(), 0x20);
}

